func directMessage(name, payloadType string) messageSpec {
	return messageSpec{Name: name, Payload: map[string]fieldSpec{"$direct": {Type: payloadType}}}
}

func directPayloadType(message messageSpec) string {
	return message.Payload["$direct"].Type
}

func fields(values ...string) map[string]fieldSpec {
	result := make(map[string]fieldSpec, len(values)/2)
	for index := 0; index < len(values); index += 2 {
		typeName := values[index+1]
		result[values[index]] = fieldSpec{Type: strings.TrimSuffix(typeName, "?"), Optional: strings.HasSuffix(typeName, "?")}
	}
	return result
}

func websocketSchema(title string, messages []messageSpec) map[string]any {
	variants := make([]any, 0, len(messages))
	for _, message := range messages {
		properties := map[string]any{
			"type":      map[string]any{"const": message.Name},
			"requestId": nullableStringSchema(),
			"roomId":    nullableStringSchema(),
		}
		requiredPayload := []string{}
		payloadProperties := map[string]any{}
		keys := sortedFieldNames(message.Payload)
		for _, name := range keys {
			field := message.Payload[name]
			payloadProperties[name] = schemaForType(field.Type)
			if !field.Optional {
				requiredPayload = append(requiredPayload, name)
			}
		}
		if payloadType := directPayloadType(message); payloadType != "" {
			properties["payload"] = schemaForType(payloadType)
		} else {
			properties["payload"] = map[string]any{"type": "object", "additionalProperties": false, "properties": payloadProperties, "required": requiredPayload}
		}
		variants = append(variants, map[string]any{"type": "object", "additionalProperties": false, "required": []string{"type", "payload"}, "properties": properties})
	}
	return map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "title": title, "version": frontendContractVersion, "oneOf": variants}
}

func nullableStringSchema() map[string]any { return map[string]any{"type": []string{"string", "null"}} }

func schemaForType(typeName string) map[string]any {
	if strings.HasSuffix(typeName, "[]") {
		return map[string]any{"type": "array", "items": schemaForType(strings.TrimSuffix(typeName, "[]"))}
	}
	switch typeName {
	case "string", "number", "boolean":
		jsonType := typeName
		if jsonType == "number" {
			jsonType = "number"
		}
		return map[string]any{"type": jsonType}
	case "EventMetadata":
		return map[string]any{"type": "object", "additionalProperties": map[string]any{"type": []string{"string", "number", "boolean"}}}
	default:
		return map[string]any{"type": "object", "x-typescript-type": typeName}
	}
}

func sortedFieldNames(values map[string]fieldSpec) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

