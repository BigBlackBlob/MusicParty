func jsonGeneratedFile(path string, value any) GeneratedFile {
	content, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		panic(err)
	}
	return GeneratedFile{Path: path, Content: append(content, '\n')}
}

func textGeneratedFile(path, value string) GeneratedFile {
	return GeneratedFile{Path: path, Content: []byte(strings.TrimSpace(value) + "\n")}
}

