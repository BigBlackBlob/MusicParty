func generatedWebSocket(client, server []messageSpec) string {
	var output strings.Builder
	output.WriteString("// Code generated by backend-go/cmd/contractgen. DO NOT EDIT.\n")
	output.WriteString("import type { ChatMessage, NowPlaying, PlayerEvent, PresenceSnapshot, QueueItem, QueuePatchOperation, RoomSummary, UserSummary } from './models'\n\n")
	writeEnvelopeTypes(&output, client, "Client")
	writeEnvelopeTypes(&output, server, "Server")
	return output.String()
}

func writeEnvelopeTypes(output *strings.Builder, messages []messageSpec, prefix string) {
	names := make([]string, 0, len(messages))
	for _, message := range messages {
		name := exportedName(message.Name) + prefix + "Envelope"
		names = append(names, name)
		fmt.Fprintf(output, "export interface %s { type: %q; requestId?: string | null; roomId?: string | null; payload: ", name, message.Name)
		if payloadType := directPayloadType(message); payloadType != "" {
			fmt.Fprintf(output, "%s }\n", payloadType)
			continue
		}
		output.WriteString("{")
		for _, fieldName := range sortedFieldNames(message.Payload) {
			field := message.Payload[fieldName]
			optional := ""
			if field.Optional {
				optional = "?"
			}
			fmt.Fprintf(output, " %s%s: %s;", fieldName, optional, field.Type)
		}
		output.WriteString(" } }\n")
	}
	fmt.Fprintf(output, "\nexport type %sEnvelope =\n  | %s\n\n", prefix, strings.Join(names, "\n  | "))
}

func exportedName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool { return r == '.' || r == '-' })
	for index := range parts {
		if parts[index] != "" {
			parts[index] = strings.ToUpper(parts[index][:1]) + parts[index][1:]
		}
	}
	return strings.Join(parts, "")
}
